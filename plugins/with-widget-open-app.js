// Tapping the Android Medical ID widget opens AntiRog.
//
// expo-widgets (SDK 58) has no "open the app" action on Android: a widget <Button target="…"> only
// sends a broadcast to the widget's provider, which re-evaluates the layout. This plugin replaces the
// provider that expo-widgets generates (EmergencyWidgetProvider.kt) with one that, for the target
// "open-app", launches the app instead. The widget layout wraps its whole content in such a button
// (src/widgets/emergency-widget.android.tsx). Every other target falls through to expo-widgets.
//
// Listed BEFORE "expo-widgets" in app.json: dangerous mods run in reverse plugin order, so this one
// then runs after expo-widgets has written its provider. After prebuild,
// android/app/src/main/java/<package>/EmergencyWidgetProvider.kt must contain "open-app".
const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('expo/config-plugins');

const WIDGET_NAME = 'EmergencyWidget';
const OPEN_APP_TARGET = 'open-app';

function providerSource(pkg) {
  return `package ${pkg}

import android.content.Context
import android.content.Intent
import expo.modules.widgets.ExpoWidgetsAppWidgetProvider

// Generated by plugins/with-widget-open-app.js. Do not edit; change the plugin instead.
class ${WIDGET_NAME}Provider : ExpoWidgetsAppWidgetProvider("${WIDGET_NAME}") {
  override fun onReceive(context: Context, intent: Intent) {
    if (intent.action == "expo.modules.widgets.ACTION_WIDGET_INTERACTION" &&
      intent.getStringExtra("expo.modules.widgets.extra.TARGET") == "${OPEN_APP_TARGET}"
    ) {
      // The widget click hands this broadcast a background-activity-start grant, so the app may be
      // brought to the front from here.
      context.packageManager.getLaunchIntentForPackage(context.packageName)?.let { launch ->
        launch.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_RESET_TASK_IF_NEEDED)
        context.startActivity(launch)
      }
      return
    }
    super.onReceive(context, intent)
  }
}
`;
}

module.exports = function withWidgetOpenApp(config) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const pkg = cfg.android?.package;
      if (!pkg) throw new Error('with-widget-open-app: android.package is required.');
      const file = path.join(
        cfg.modRequest.platformProjectRoot,
        'app/src/main/java',
        ...pkg.split('.'),
        `${WIDGET_NAME}Provider.kt`,
      );
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, providerSource(pkg));
      return cfg;
    },
  ]);
};
